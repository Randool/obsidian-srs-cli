export function resolveLang(env = process.env) {
  const raw = env.SRS_LANG || env.LC_ALL || env.LC_MESSAGES || env.LANG || "";
  const v = String(raw).toLowerCase();
  if (v.startsWith("en")) return "en";
  return "zh";
}

export function makeT(lang = resolveLang()) {
  const dict = DICT[lang] || DICT.zh;
  return (key, params = {}) => {
    let s = dict[key] ?? DICT.zh[key] ?? key;
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };
}

export const t = makeT();
